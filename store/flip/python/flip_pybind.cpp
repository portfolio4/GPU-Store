namespace impl {

template <typename T>
py::bytes toBytes(T const& t) {
    return py::bytes(reinterpret_cast<const char*>(&t), sizeof(t));
}

template <typename T>
T fromBytes(py::bytes bytes) {
    char* buffer;
    ssize_t length;
    if (PYBIND11_BYTES_AS_STRING_AND_SIZE(bytes.ptr(), &buffer, &length)) {
        py::pybind11_fail("Unable to extract bytes contents");
    }
    if (static_cast<size_t>(length) < sizeof(T)) {
        py::pybind11_fail(std::format("byte contents is too short for object of size {}", sizeof(T)));
    }
    return *reinterpret_cast<T const*>(buffer);
}

}

